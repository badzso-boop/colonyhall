// Counts the numbers under the strata (docs/18, 4.7) from git and the
// repository, and writes them to site/src/data/counters.json. The output is
// committed, so the site's build needs neither the network nor the full
// history. Run it from anywhere in the repository (npm --prefix site run
// counters), on main, after a round is merged; then commit the file.
//
//   rounds      rounds marked "shipped" in site/src/data/strata.json
//   commits     git rev-list --count HEAD
//   migrations  the goose files in migrations/
//   tests       Go test functions (func TestXxx) plus Vitest and Node test
//               cases (it(...) / test(...)) in web/ and internal/httpserver/web/
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const HERE = new URL(".", import.meta.url).pathname;
const REPO = execFileSync("git", ["rev-parse", "--show-toplevel"], { cwd: HERE, encoding: "utf8" }).trim();
const OUT = join(REPO, "site", "src", "data", "counters.json");

const walk = (dir, keep) => {
  let out = [];
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name === "dist" || name.startsWith(".")) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out = out.concat(walk(p, keep));
    else if (keep(p)) out.push(p);
  }
  return out;
};
const count = (files, re) => files.reduce((n, f) => n + (readFileSync(f, "utf8").match(re) || []).length, 0);

const strata = JSON.parse(readFileSync(join(REPO, "site", "src", "data", "strata.json"), "utf8"));
const rounds = strata.rounds.filter((r) => r.state === "shipped").length;
const commits = Number(execFileSync("git", ["rev-list", "--count", "HEAD"], { cwd: REPO, encoding: "utf8" }).trim());
const migrations = readdirSync(join(REPO, "migrations")).filter((f) => /^\d+_.*\.sql$/.test(f)).length;

const goTests = walk(REPO, (p) => p.endsWith("_test.go"));
const jsTests = [join(REPO, "web", "src"), join(REPO, "internal", "httpserver", "web")]
  .flatMap((d) => { try { return walk(d, (p) => /\.test\.(?:[cm]?js|tsx?)$/.test(p)); } catch { return []; } });
const tests = count(goTests, /^func Test[A-Z0-9_]\w*\(/gm) + count(jsTests, /^\s*(?:it|test)(?:\.each\([^)]*\))?\(\s*["'`]/gm);

const result = { _comment: "Generated by site/scripts/counters.mjs; do not edit by hand.", rounds, commits, migrations, tests };
writeFileSync(OUT, JSON.stringify(result, null, 1) + "\n");
console.log(`counters: ${rounds} rounds, ${commits} commits, ${migrations} migrations, ${tests} tests -> ${OUT.slice(REPO.length + 1)}`);
