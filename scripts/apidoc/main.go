// Command apidoc writes docs/en/api.md, a plain Markdown reference of the
// REST API, from api/openapi.yaml (round 48). `make gen` runs it and
// `make gen-check` fails when the reference is stale. Run it from the
// repository root.
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
)

const (
	in  = "api/openapi.yaml"
	out = "docs/en/api.md"
)

func main() {
	doc, err := openapi3.NewLoader().LoadFromFile(in)
	if err != nil {
		fail(err)
	}
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("# REST API reference\n\n")
	w("<!-- Generated by scripts/apidoc from api/openapi.yaml (make gen); do not edit. -->\n\n")
	w("%s\n\n", strings.TrimSpace(doc.Info.Description))
	w("Base path: `/api/v1`. **Auth** says whether an operation needs a signed-in caller (a Bearer token or the browser session). The schemas are listed at the end; the source of truth is [`api/openapi.yaml`](../../api/openapi.yaml).\n\n")

	type op struct {
		method, path string
		o            *openapi3.Operation
		pathParams   openapi3.Parameters
	}
	byTag := map[string][]op{}
	for _, path := range doc.Paths.InMatchingOrder() {
		item := doc.Paths.Value(path)
		for method, o := range item.Operations() {
			tag := "other"
			if len(o.Tags) > 0 {
				tag = o.Tags[0]
			}
			byTag[tag] = append(byTag[tag], op{method, path, o, item.Parameters})
		}
	}
	tags := make([]string, 0, len(byTag))
	for t := range byTag {
		tags = append(tags, t)
	}
	sort.Strings(tags)

	w("## Contents\n\n")
	for _, t := range tags {
		w("- [%s](#%s) (%d)\n", t, t, len(byTag[t]))
	}
	w("- [Schemas](#schemas)\n\n")

	public := func(o *openapi3.Operation) bool { return o.Security != nil && len(*o.Security) == 0 }
	for _, t := range tags {
		ops := byTag[t]
		sort.Slice(ops, func(i, j int) bool {
			if ops[i].path != ops[j].path {
				return ops[i].path < ops[j].path
			}
			return ops[i].method < ops[j].method
		})
		w("## %s\n\n", t)
		for _, x := range ops {
			w("### `%s %s`\n\n", x.method, x.path)
			auth := "signed in"
			if public(x.o) {
				auth = "public"
			}
			w("`%s` · Auth: %s\n\n", x.o.OperationID, auth)
			if d := strings.TrimSpace(x.o.Description); d != "" {
				w("%s\n\n", d)
			}
			params := append(openapi3.Parameters{}, x.pathParams...)
			params = append(params, x.o.Parameters...)
			if len(params) > 0 {
				w("| Parameter | In | Type | Required | Description |\n| --- | --- | --- | --- | --- |\n")
				for _, p := range params {
					v := p.Value
					w("| `%s` | %s | %s | %s | %s |\n", v.Name, v.In, schemaType(v.Schema), yes(v.Required), cell(v.Description))
				}
				w("\n")
			}
			if rb := x.o.RequestBody; rb != nil && rb.Value != nil {
				for ct, mt := range rb.Value.Content {
					w("Request body (`%s`%s): %s\n\n", ct, map[bool]string{true: ", required"}[rb.Value.Required], schemaType(mt.Schema))
				}
			}
			codes := make([]string, 0)
			for code := range x.o.Responses.Map() {
				if code != "default" {
					codes = append(codes, code)
				}
			}
			sort.Strings(codes)
			if len(codes) > 0 {
				w("| Response | Body |\n| --- | --- |\n")
				for _, code := range codes {
					r := x.o.Responses.Value(code).Value
					body := cell(deref(r.Description))
					for ct, mt := range r.Content {
						body = fmt.Sprintf("%s (`%s`)", schemaType(mt.Schema), ct)
						if d := deref(r.Description); d != "" {
							body = cell(d) + ": " + body
						}
					}
					w("| %s | %s |\n", code, body)
				}
				w("\n")
			}
		}
	}

	w("## Schemas\n\n")
	names := make([]string, 0, len(doc.Components.Schemas))
	for n := range doc.Components.Schemas {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		s := doc.Components.Schemas[n].Value
		w("### %s\n\n", n)
		if d := strings.TrimSpace(s.Description); d != "" {
			w("%s\n\n", d)
		}
		if len(s.Enum) > 0 {
			w("One of: %s\n\n", enum(s.Enum))
		}
		if len(s.Properties) == 0 {
			if t := schemaType(doc.Components.Schemas[n]); t != "object" {
				w("Type: %s\n\n", t)
			}
			continue
		}
		req := map[string]bool{}
		for _, r := range s.Required {
			req[r] = true
		}
		props := make([]string, 0, len(s.Properties))
		for p := range s.Properties {
			props = append(props, p)
		}
		sort.Strings(props)
		w("| Field | Type | Required | Description |\n| --- | --- | --- | --- |\n")
		for _, p := range props {
			ref := s.Properties[p]
			desc := ""
			if ref.Value != nil {
				desc = ref.Value.Description
				if len(ref.Value.Enum) > 0 {
					desc = strings.TrimSpace(desc + " One of: " + enum(ref.Value.Enum) + ".")
				}
			}
			w("| `%s` | %s | %s | %s |\n", p, schemaType(ref), yes(req[p]), cell(desc))
		}
		w("\n")
	}

	if err := os.WriteFile(out, []byte(strings.TrimRight(b.String(), "\n")+"\n"), 0o644); err != nil {
		fail(err)
	}
}

// schemaType names a schema: a link for a component, the item type for an
// array, the type and format otherwise.
func schemaType(ref *openapi3.SchemaRef) string {
	if ref == nil {
		return ""
	}
	if ref.Ref != "" {
		name := ref.Ref[strings.LastIndex(ref.Ref, "/")+1:]
		return fmt.Sprintf("[%s](#%s)", name, strings.ToLower(name))
	}
	s := ref.Value
	if s == nil {
		return ""
	}
	switch {
	case s.Type.Is("array"):
		return schemaType(s.Items) + "[]"
	case len(s.OneOf) > 0 || len(s.AnyOf) > 0 || len(s.AllOf) > 0:
		var parts []string
		for _, list := range []openapi3.SchemaRefs{s.OneOf, s.AnyOf, s.AllOf} {
			for _, x := range list {
				parts = append(parts, schemaType(x))
			}
		}
		return strings.Join(parts, " \\| ")
	}
	t := strings.Join(s.Type.Slice(), "/")
	if t == "" {
		t = "any"
	}
	if s.Format != "" {
		t += " (" + s.Format + ")"
	}
	if s.Nullable {
		t += ", nullable"
	}
	return t
}

func enum(values []any) string {
	parts := make([]string, len(values))
	for i, v := range values {
		parts[i] = fmt.Sprintf("`%v`", v)
	}
	return strings.Join(parts, ", ")
}

func cell(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	return strings.ReplaceAll(s, "|", "\\|")
}

func yes(b bool) string {
	if b {
		return "yes"
	}
	return ""
}

func deref(s *string) string {
	if s == nil {
		return ""
	}
	return *s
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "apidoc:", err)
	os.Exit(1)
}
